-- Run this in Supabase SQL Editor before deploying.
create table if not exists public.portfolio_visits (
  id bigint generated by default as identity primary key,
  visited_at timestamptz not null default now(),
  ip_address text,
  city text,
  region text,
  country text,
  latitude double precision,
  longitude double precision,
  timezone text,
  user_agent text,
  referrer text
);

alter table public.portfolio_visits enable row level security;

-- No anon/authenticated policies are created. Reads and writes are performed only
-- by the server-side Vercel functions using the service-role key, which must stay secret.
revoke all on table public.portfolio_visits from anon, authenticated;
grant all on table public.portfolio_visits to service_role;
